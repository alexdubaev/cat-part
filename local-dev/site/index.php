<?php

declare(strict_types=1);

/**
 * Единая точка входа (front controller). docroot должен указывать на /public.
 * Bootstrap (автозагрузка/конфиг/БД) — общий с CLI-скриптами; здесь добавляем
 * обработчик исключений, сессию и маршрутизацию.
 *
 * Карты редиректов (donor: app/redirects.php, 2701 запись со старых .html) у нас нет:
 * сайт новый, переезжать не с чего. Появится история URL — появится и карта.
 */

// Bootstrap ищем рядом (плоская раскладка: index.php в корне сайта рядом с app/)
// либо уровнем выше (docroot указывает на /public). Работает на любом хостинге.
$bootstrap = is_file(__DIR__ . '/app/bootstrap.php')
    ? __DIR__ . '/app/bootstrap.php'
    : dirname(__DIR__) . '/app/bootstrap.php';

/**
 * 🔥 Обработчик исключений ставим ДО bootstrap — намеренно.
 *
 * У донора его нет вовсе: упал PDO (БД недоступна, кончились коннекты) — и посетитель
 * получает белый экран, причём с кодом 200, потому что заголовок никто не переставил.
 * Поисковик такую страницу с удовольствием проиндексирует как «валидную и пустую».
 *
 * Само подключение к БД происходит внутри bootstrap (App::boot → new Database), поэтому
 * регистрация ПОСЛЕ него не поймала бы самый вероятный сбой. Отсюда же требование к телу
 * обработчика: он не имеет права рассчитывать, что App поднялось, — все обращения к
 * конфигу и вьюхам защищены try/catch.
 */
set_exception_handler(static function (\Throwable $e): void {
    // Лог — всегда и в первую очередь: это единственный след, если наружу мы ничего не скажем.
    error_log(sprintf(
        '[catpart] %s: %s @ %s:%d',
        $e::class,
        $e->getMessage(),
        $e->getFile(),
        $e->getLine()
    ));

    $debug = false;
    try {
        $debug = (bool) \App\Core\App::config('app.debug');
    } catch (\Throwable) {
        /**
         * App не инициализировано — то есть сбой случился ВНУТРИ bootstrap, и это как раз
         * самый вероятный инцидент (легла БД). Спросить конфиг не у кого, но флаг читается
         * из того же места, откуда его берёт config.php ('debug' => getenv('APP_DEBUG')),
         * так что подмены источника тут нет.
         *
         * Если переменной нет — остаёмся в боевом режиме и молчим: отсутствие конфига
         * не повод раскрывать наружу имя БД, пользователя и хост из сообщения PDO.
         */
        $debug = (bool) (getenv('APP_DEBUG') ?: false);
    }

    /**
     * Сбрасываем ВСЕ открытые буферы вывода до единого.
     *
     * Без этого вылезает франкенштейн, и вот почему: View::renderFile() делает ob_start(),
     * а закрывающий ob_get_clean() до конца не доживает, если шаблон бросил исключение
     * посреди рендера (типичный случай — упала БД, шапка/вьюха дёрнули App::config).
     * Полстраницы остаются висеть в буфере, PHP сам сольёт их наружу на завершении,
     * и наша аварийная страница приклеится ровно в середину оборванного тега.
     * Проверено на живом сбое: обрывок ушёл в атрибут action="…" незакрытой формы.
     */
    while (ob_get_level() > 0) {
        ob_end_clean();
    }

    // HEAD не должен получить тело даже в аварии — фильтр снесло чисткой выше, ставим заново.
    if (strtoupper((string) ($_SERVER['REQUEST_METHOD'] ?? 'GET')) === 'HEAD') {
        ob_start(static fn (string $buffer): string => '');
    }

    // Уровень буферов, ниже которого опускаться нельзя (0, либо 1 — фильтр HEAD).
    $baseLevel = ob_get_level();

    if (!headers_sent()) {
        http_response_code(500);
        header('Content-Type: text/html; charset=utf-8');
    }

    // Подробности — только при app.debug. В проде текст ошибки наружу не идёт:
    // сообщение PDO содержит имя БД, пользователя и хост.
    $details = $debug
        ? $e::class . ': ' . $e->getMessage() . "\n" . $e->getFile() . ':' . $e->getLine()
            . "\n\n" . $e->getTraceAsString()
        : '';

    try {
        // 'message' — ключ, который читает pages/error.php (не 'text': молча подставит свой дефолт).
        echo \App\Core\View::render('pages.error', [
            'page'    => ['title' => 'Ошибка сервера (500)'],
            'code'    => 500,
            'message' => $debug
                ? $details
                : 'Страница временно недоступна. Мы уже знаем о проблеме — попробуйте обновить её через минуту.',
        ]);
    } catch (\Throwable) {
        /**
         * Аварийная страница сама не отрисовалась. Это НЕ экзотика, а основной путь при
         * лежащей БД: pages/error.php зовёт url() → App::config(), а App как раз и не
         * поднялось — вьюха падает ровно там же, где упал сайт.
         *
         * И падает она посреди рендера, оставив за собой открытый ob_start() из
         * View::renderFile(). Не подчистив его здесь, мы вклеим свой запасной HTML внутрь
         * оборванного шаблона: проверено — обрывок уехал в атрибут action="…" незакрытой
         * формы, наружу поехал нечитаемый гибрид. Чистим до базового уровня (фильтр HEAD,
         * если он есть, обязан уцелеть — иначе тело уйдёт в ответ на HEAD).
         */
        while (ob_get_level() > $baseLevel) {
            ob_end_clean();
        }

        // Минимальный самодостаточный HTML: ни БД, ни конфига, ни шаблонов — лишь бы не белый экран.
        echo '<!DOCTYPE html><html lang="ru"><meta charset="utf-8">'
            . '<title>Ошибка сервера</title>'
            . '<h1>500 — ошибка сервера</h1>'
            . '<p>Страница временно недоступна. Попробуйте обновить её через минуту.</p>';
        if ($details !== '') {
            echo '<pre>' . htmlspecialchars($details, ENT_QUOTES | ENT_SUBSTITUTE, 'UTF-8') . '</pre>';
        }
    }
});

$app = require $bootstrap;

\App\Core\Session::start();

(require BASE_PATH . '/app/routes.php')($app->router);

$method = strtoupper((string) ($_SERVER['REQUEST_METHOD'] ?? 'GET'));
$path = (string) (parse_url((string) ($_SERVER['REQUEST_URI'] ?? '/'), PHP_URL_PATH) ?: '/');

/**
 * HEAD = GET без тела. Маршрутизацию делает роутер (см. Router::dispatch), а тело
 * отсекаем здесь: обработчик выводит его как обычно, а фильтр буфера возвращает пустую
 * строку. Именно фильтром, а не ob_end_clean(): половина контроллеров завершается через
 * exit (sitemap, notFound), и на exit PHP сам сбрасывает буферы — «почистить в конце»
 * просто не успело бы. Заголовки при этом уходят полностью, как и требует HEAD.
 */
if ($method === 'HEAD') {
    ob_start(static fn (string $buffer): string => '');
}

if (!$app->router->dispatch($method, $path)) {
    // Текст 404 живёт в одном месте — Core\Controller::NOT_FOUND_TEXT. У донора он был
    // продублирован здесь и в контроллере, слово в слово, с упоминанием подшипников.
    echo \App\Core\Controller::renderNotFound();
}
